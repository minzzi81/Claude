def make_post(i: int, s: str) -> tuple[dict, list[dict]]:
    p = NAME[s]
    paras = [R.choice(COMMON).format(p=p) for _ in range(R.randint(1, 2))]
    if s == "큐커":
        paras += R.sample(DIET, R.randint(1, 3)) + R.sample(COOK, R.randint(1, 2))
    else:
        paras += R.sample(FUNC[s], R.randint(2, 3))
        if s == "냉장고" and R.random() < 0.15:
            paras += OTHER_DIET
    R.shuffle(paras)
    pid = f"synthetic:{i}"
    post = {"post_id": pid, "source": "synthetic", "url": "", "title": f"스마트싱스 {p} 사용 후기",
            "text": "\n".join(paras), "created_at": "", "author_hash": "", "query": f"스마트싱스 {p}",
            "stratum": s, "sponsored": False}
    pool = (CMT_DIET + CMT_COMMON) if s == "큐커" else (CMT_FUNC + CMT_COMMON)
    cmts = [{"comment_id": f"{pid}:{j}", "post_id": pid, "source": "synthetic",
             "text": R.choice(pool), "created_at": ""} for j in range(R.randint(4, 10))]
    return post, cmts


def main():
    posts, comments = [], []
    i = 0
    for s, n in QUOTA.items():
        for _ in range(n):
            p, cs = make_post(i, s)
            posts.append(p)
            comments += cs
            i += 1
    OUT.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(posts).to_csv(OUT / "posts.csv", index=False, encoding="utf-8-sig")
    pd.DataFrame(comments).to_csv(OUT / "comments.csv", index=False, encoding="utf-8-sig")
    print(f"[가상 데이터] posts={len(posts)} comments={len(comments)} -> {OUT}")


if __name__ == "__main__":
    main()
